def _wrap(text: str, indent: str, width: int = 79) -> str:
    """Return a Python string literal that fits in ``width`` columns.

    Long text becomes implicitly concatenated literals in parentheses.

    Args:
        text: The string value.
        indent: Indent of the line the literal starts on.
        width: Maximum line length.

    Returns:
        Python source for the literal (no trailing comma).
    """
    if len(indent) + len(repr(text)) + 1 <= width:
        return repr(text)
    room = max(20, width - len(indent) - 8)
    chunks, line = [], ""
    for word in text.split(" "):
        if line and len(line) + len(word) + 1 > room:
            chunks.append(line + " ")
            line = word
        else:
            line = f"{line} {word}" if line else word
    chunks.append(line)
    inner = indent + "    "
    return "(\n" + "\n".join(f"{inner}{c!r}" for c in chunks) \
        + f"\n{indent})"


def _py_list(name: str, items: List[str]) -> str:
    """Return a Python list assignment, one item per line.

    Args:
        name: Variable name.
        items: Python source of each item.

    Returns:
        Source code.
    """
    if not items:
        return f"{name} = []"
    return "\n".join([f"{name} = ["] + [f"    {i}," for i in items] + ["]"])


def _column_tuple(values: List[str]) -> str:
    """Return a tuple literal laid out one value per line.

    Args:
        values: String values of the tuple.

    Returns:
        Source code indented for a list item.
    """
    body = "\n".join(f"        {_wrap(v, '        ')}," for v in values)
    return f"(\n{body}\n    )"


def _notebook(cells: List[Tuple[str, str]]) -> str:
    """Return a notebook in the Databricks notebook source format.

    Args:
        cells: (kind, text) pairs; kind is ``markdown`` or ``code``.

    Returns:
        The ``.py`` file content.
    """
    parts = []
    after_def = False
    for kind, text in cells:
        text = text.strip("\n")
        if kind == "markdown":
            lines = ["%md"] + text.splitlines()
            text = "\n".join("# MAGIC " + line if line else "# MAGIC"
                             for line in lines)
        else:
            # PEP 8: two blank lines around top-level functions. The cell
            # break gives one, so pad the cell that defines or follows one.
            defines = text.startswith("def ") or "\ndef " in text
            if defines or after_def:
                text = "\n" + text
            after_def = defines
        parts.append(text)
    return NOTEBOOK_HEADER + "\n" + CELL_BREAK.join(parts) + "\n"


def _widgets(names: List[Tuple[str, str, str]]) -> str:
    """Return the widget cell of a notebook.

    Job parameters arrive as widgets of the same name.

    Args:
        names: (name, default, label) per widget.

    Returns:
        Source code that declares and reads every widget.
    """
    lines = []
    for n, d, label in names:
        line = f"dbutils.widgets.text({n!r}, {d!r}, {label!r})"
        if len(line) > 79:
            line = (f"dbutils.widgets.text({n!r}, {d!r},\n"
                    f"                     {label!r})")
        lines.append(line)
    lines.append("")
    lines += [f"{n} = dbutils.widgets.get({n!r})" for n, _, _ in names]
    return "\n".join(lines)


def _library_cell(module: str) -> str:
    """Return the cell that imports the shared library from the bundle.

    Args:
        module: Module of ``databricks_de_common`` to import.

    Returns:
        Source code.
    """
    return "\n".join([
        "import os",
        "import sys",
        "",
        "# The shared library is the bundle's src/ folder. bundle_root is",
        "# set by the job; interactive runs fall back to the repo layout.",
        "LIBRARY = (os.path.join(bundle_root, \"src\") if bundle_root",
        "           else os.path.abspath(os.path.join(\"..\", \"..\", "
        "\"src\")))",
        "if LIBRARY not in sys.path:",
        "    sys.path.append(LIBRARY)",
        "",
        f"from databricks_de_common import {module}  # noqa: E402",
    ])


