"""Render the code Databricks runs from the specs.

Rendered files are owned by this module: never edit them by hand. Change
the spec (``models/**.yml``) or its SELECT (``models/**.sql``) and run
``python -m dbde render``. ``python -m dbde render --check`` fails when a
rendered file is out of date, so CI catches hand edits.

Rendered output:

* ``databricks.yml``: the Asset Bundle, its variables and targets (from
  ``dbde.yml``).
* ``resources/dbde_daily_load.job.yml``: the daily Lakeflow job. One task
  per silver notebook and per gold load procedure, in dependency order,
  with data quality tasks between the layers.
* ``resources/dbde_table_maintenance.job.yml``: weekly OPTIMIZE and VACUUM.
* ``resources/genie_<name>.yml``: one Genie space per ``models/genie``
  spec, and ``genie/<Name>.geniespace.json`` (see ``dbde/genie.py``).
* ``notebooks/silver/nb_silver_<schema>_<table>.py``: one PySpark notebook
  per silver table (Databricks notebook source format).
* ``notebooks/ops/nb_ops_*.py``: run a gold load procedure, run the data
  quality tests of a layer, maintain the tables.
* ``gold/<schema>/tables/<Table>.sql``: the gold table DDL.
* ``gold/<schema>/procedures/Load<Table>.sql``: the one stored procedure
  per gold table (MERGE; SCD2 for type 2 dimensions).
* ``gold/<schema>/metric_views/Metric<Process>.sql``: a metric view per
  fact with measures.
* ``gold/ops/...``: the data quality log table and procedures, the
  procedure that runs every gold load in order, and Genie grants.

Rendered SQL never names a catalog. It uses ``${bronze_catalog}``,
``${silver_catalog}`` and ``${gold_catalog}``; ``python -m dbde deploy``
replaces them with the target's catalogs. Top-level statements are
separated by a ``-- GO`` line so the deploy can run them one at a time.
"""

