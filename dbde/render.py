def render_all(project: Project) -> Dict[str, str]:
    """Render every owned file.

    Args:
        project: The loaded project.

    Returns:
        Relative path -> file content.
    """
    out: Dict[str, str] = {"databricks.yml": bundle_yml(project)}
    out[f"resources/{JOB}.job.yml"] = daily_job_yml(project)
    out[f"resources/{MAINTENANCE_JOB}.job.yml"] = maintenance_job_yml(project)
    for model in project.silver():
        out[notebook_path(model)] = _notebook(_silver_cells(project, model))
    out["notebooks/ops/nb_ops_load_gold.py"] = _notebook(
        _ops_load_gold_cells())
    out["notebooks/ops/nb_ops_run_tests.py"] = _notebook(
        _ops_run_tests_cells())
    out["notebooks/ops/nb_ops_maintain_tables.py"] = _notebook(
        _ops_maintain_cells(project))
    for model in project.gold():
        base = f"gold/{model.schema}"
        out[f"{base}/tables/{model.name}.sql"] = gold_table_sql(project, model)
        out[f"{base}/procedures/Load{model.name}.sql"] = gold_procedure_sql(
            project, model)
        if model.metric_view:
            out[f"{base}/metric_views/{model.metric_view}.sql"] = \
                genie.metric_view_sql(project, model)
    out["gold/ops/tables/DataQualityResult.sql"] = ops_table_sql()
    out["gold/ops/procedures/RunDataQualityTests.sql"] = ops_tests_sql(project)
    if project.gold():
        out["gold/ops/procedures/RunGoldLoads.sql"] = ops_gold_loads_sql(
            project)
    for space in project.spaces.values():
        out[f"genie/{space.name}.geniespace.json"] = genie.space_json(
            project, space)
        out[f"resources/{space.resource_name}.yml"] = _yaml(
            [GENERATED.format(spec=space.path.relative_to(
                project.config.root).as_posix()),
             "python -m dbde deploy writes file_path for the target first."],
            genie.space_resource(project, space))
        if space.groups:
            out[f"gold/ops/grants/{space.name}.sql"] = genie.grants_sql(
                project, space)
    return out


def gold_deploy_order(project: Project) -> List[str]:
    """Return the rendered gold SQL files in the order they must run.

    Args:
        project: The loaded project.

    Returns:
        Relative paths: ops table, tables, procedures, metric views, ops
        procedures, grants.
    """
    order = project.load_order(project.gold())
    files = ["gold/ops/tables/DataQualityResult.sql"]
    files += [f"gold/{m.schema}/tables/{m.name}.sql" for m in order]
    files += [f"gold/{m.schema}/procedures/Load{m.name}.sql" for m in order]
    files += [f"gold/{m.schema}/metric_views/{m.metric_view}.sql"
              for m in order if m.metric_view]
    files += ["gold/ops/procedures/RunDataQualityTests.sql"]
    if order:
        files += ["gold/ops/procedures/RunGoldLoads.sql"]
    files += [f"gold/ops/grants/{s.name}.sql"
              for s in project.spaces.values() if s.groups]
    return files


def owned_files(root: Path) -> List[str]:
    """Return the rendered files currently on disk.

    Args:
        root: Project root folder.

    Returns:
        Relative paths with forward slashes.
    """
    found = set()
    for pattern in OWNED_GLOBS:
        for path in root.glob(pattern):
            if path.is_file():
                found.add(path.relative_to(root).as_posix())
    return sorted(found)


def write(project: Project, check: bool = False) -> List[str]:
    """Write the rendered files, or report what is out of date.

    Args:
        project: The loaded project.
        check: When True, change nothing and only report.

    Returns:
        Messages: files written / out of date / removed / stale.
    """
    root = project.config.root
    rendered = render_all(project)
    messages = []
    for path, content in sorted(rendered.items()):
        target = root / path
        current = target.read_text(encoding="utf-8") if target.exists() \
            else None
        if current == content:
            continue
        messages.append(f"{'out of date' if check else 'wrote'}: {path}")
        if not check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")
    for path in owned_files(root):
        if path not in rendered:
            messages.append(f"{'stale' if check else 'removed'}: {path}")
            if not check:
                stale = root / path
                stale.unlink()
                for folder in stale.parents:
                    if folder == root or any(folder.iterdir()):
                        break
                    folder.rmdir()
    return messages
