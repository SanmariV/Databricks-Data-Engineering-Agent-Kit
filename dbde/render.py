def _ops_maintain_cells(project: Project) -> List[Tuple[str, str]]:
    """Return the cells of the table maintenance notebook."""
    retention = int(project.config.maintenance.get("vacuum_retain_hours",
                                                   168))
    tables = [repr((m.layer, m.key)) for m in project.silver()
              + project.gold()]
    tables.append(repr(("gold", "ops.DataQualityResult")))
    intro = f"""# Ops: table maintenance

Runs `OPTIMIZE` and then `VACUUM ... RETAIN {retention} HOURS` on every
silver and gold table (DE Policy v2: Delta tables are actively maintained
before they are promoted to production). Scheduled weekly by the
`{MAINTENANCE_JOB}` job. Tables that do not exist yet are skipped.

{GENERATED.format(spec="every silver and gold spec")}"""
    settings = "\n".join([
        "# (layer, schema.Table) for every table the kit builds.",
        _py_list("TABLES", tables),
        f"RETAIN_HOURS = {retention}",
    ])
    run = "\n".join([
        "CATALOGS = {\"silver\": silver_catalog, \"gold\": gold_catalog}",
        "ops.maintain_tables(spark, [f\"{CATALOGS[layer]}.{key}\"",
        "                            for layer, key in TABLES], RETAIN_HOURS)",
    ])
    return [
        ("markdown", intro),
        ("markdown", "## Parameters"),
        ("code", _widgets(CATALOG_WIDGETS)),
        ("markdown", "## Shared library"),
        ("code", _library_cell("ops")),
        ("markdown", "## Tables"),
        ("code", settings),
        ("markdown", "## Run"),
        ("code", run),
    ]


