def _type(data_type: str) -> str:
    """Return a spec type in the upper-case style of the rendered SQL."""
    return data_type.upper().replace(" ", "")


def _unknown_literal(data_type: str) -> str:
    """Return the business key value used for the unknown member row.

    Args:
        data_type: Spec type of the key.

    Returns:
        A Databricks SQL literal.
    """
    base = data_type.split("(")[0]
    if base in ("string", "varchar", "char"):
        return "'-1'"
    if base == "date":
        return "DATE'1900-01-01'"
    if base.startswith("timestamp"):
        return "TIMESTAMP'1900-01-01 00:00:00'"
    if base == "boolean":
        return "false"
    return "-1"


def _gold_columns(model: Model) -> List[Tuple[str, str, bool, str]]:
    """Return every physical column of a gold table in policy order.

    Args:
        model: A gold model.

    Returns:
        (name, type, nullable, comment): ``_SK``, business keys, data,
        ``StartDate``/``EndDate``/``IsCurrent`` (type 2 only), audit.
    """
    cols = [(model.surrogate_key, "BIGINT", False,
             f"Surrogate key of {model.name} (-1 is the unknown member).")]
    cols += [(c.name, _type(c.data_type), False, _one_line(c.description))
             for c in model.columns if c.business_key]
    cols += [(c.name, _type(c.data_type), True, _one_line(c.description))
             for c in model.data_columns]
    if model.is_scd2:
        cols += [(n, t, False, d) for n, t, d in SCD_TYPES]
    cols += [(n, t, False, d) for n, t, d in AUDIT_TYPES]
    return cols


def _one_line(text) -> str:
    """Return text on one line."""
    return " ".join(str(text or "").split())


def _schema_statement(schema: str) -> str:
    """Return a statement that creates a gold schema when it is missing."""
    return f"CREATE SCHEMA IF NOT EXISTS {TOKENS['gold']}.{schema};\n{GO}"


def _fk_name(model: Model, column: str) -> str:
    """Return the foreign key constraint name of a reference column."""
    return f"{model.name}_{column}_fk"


def gold_table_sql(project: Project, model: Model) -> str:
    """Return the idempotent DDL of a gold table.

    Creates the table when missing (columns in policy order, comments from
    the spec, an informational primary key on ``_SK`` and foreign keys to
    the referenced dimensions), adds columns added to the spec since, keeps
    the comments in step with the spec and inserts the unknown member row of
    a dimension.

    Args:
        project: The loaded project.
        model: A gold model.

    Returns:
        Databricks SQL statements separated by ``-- GO`` lines.
    """
    spec = model.path.relative_to(project.config.root).as_posix()
    rel = project.relation(model)
    cols = _gold_columns(model)
    width = max(len(n) for n, _, _, _ in cols)
    body = [f"    {n.ljust(width)} {t}{'' if null else ' NOT NULL'} "
            f"COMMENT {sql_string(c)}" for n, t, null, c in cols]
    body.append(f"    CONSTRAINT {model.name}_pk "
                f"PRIMARY KEY ({model.surrogate_key})")
    refs = [(c, project.models[c.references]) for c in model.columns
            if c.references and c.references in project.models]
    for col, dim in refs:
        body.append(f"    CONSTRAINT {_fk_name(model, col.name)} "
                    f"FOREIGN KEY ({col.name}) REFERENCES "
                    f"{project.relation(dim)} ({dim.surrogate_key})")
    lines = [f"-- Gold table {model.key} ({model.kind}"
             + (f", SCD type {model.scd_type}" if model.scd_type else "")
             + ").", f"-- {GENERATED.format(spec=spec)}", "",
             _schema_statement(model.schema), "",
             f"CREATE TABLE IF NOT EXISTS {rel} (",
             ",\n".join(body), ")", "USING DELTA",
             f"COMMENT {sql_string(model.description)};", GO, ""]
    table = model.name.lower()
    nullable = [(n, t, c) for n, t, null, c in cols if null]
    if nullable or refs:
        lines += ["-- Columns and keys added to the spec after the first "
                  "deploy.",
                  "-- Only nullable columns can be added; a type change "
                  "needs a migration",
                  "-- (standards, section 7.5).", "BEGIN"]
        for name, data_type, comment in nullable:
            lines += [
                "    IF NOT EXISTS (",
                f"        SELECT 1 FROM {TOKENS['gold']}.information_schema"
                ".columns",
                f"        WHERE table_schema = '{model.schema}' "
                f"AND table_name = '{table}'",
                f"            AND lower(column_name) = '{name.lower()}'",
                "    ) THEN",
                f"        ALTER TABLE {rel} ADD COLUMNS (",
                f"            {name} {data_type} "
                f"COMMENT {sql_string(comment)}",
                "        );",
                "    END IF;"]
        for col, dim in refs:
            fk = _fk_name(model, col.name)
            lines += [
                "    IF NOT EXISTS (",
                f"        SELECT 1 FROM {TOKENS['gold']}.information_schema"
                ".table_constraints",
                f"        WHERE table_schema = '{model.schema}' "
                f"AND lower(constraint_name) = '{fk.lower()}'",
                "    ) THEN",
                f"        ALTER TABLE {rel} ADD CONSTRAINT {fk}",
                f"            FOREIGN KEY ({col.name}) REFERENCES "
                f"{project.relation(dim)} ({dim.surrogate_key});",
                "    END IF;"]
        lines += ["END;", GO, ""]
    lines += ["-- Descriptions: Unity Catalog comments follow the spec "
              "(Genie reads them).", "BEGIN",
              f"    COMMENT ON TABLE {rel} IS "
              f"{sql_string(model.description)};"]
    lines += [f"    ALTER TABLE {rel} ALTER COLUMN {n} COMMENT "
              f"{sql_string(c)};" for n, _, _, c in cols]
    lines += ["END;", GO]
    if model.kind == "dimension":
        names = [model.surrogate_key] + model.business_keys
        values = ["-1"] + [_unknown_literal(c.data_type)
                           for c in model.columns if c.business_key]
        if model.is_scd2:
            names += ["StartDate", "EndDate", "IsCurrent"]
            values += ["DATE'1900-01-01'", "DATE'9999-12-31'", "true"]
        names += AUDIT_COLUMNS
        values += ["'deploy'", "current_timestamp()", "'deploy'",
                   "current_timestamp()"]
        lines += ["", "-- Unknown member: facts point here when a key has "
                      "no dimension row.",
                  f"INSERT INTO {rel} (",
                  "    " + ",\n    ".join(names), ")",
                  "SELECT",
                  "    " + ",\n    ".join(values),
                  f"WHERE NOT EXISTS (SELECT 1 FROM {rel} "
                  f"WHERE {model.surrogate_key} = -1);", GO]
    return "\n".join(lines) + "\n"


def _changed(left: str, right: str, columns: List[str],
             indent: str) -> str:
    """Return a null-safe "any column differs" predicate.

    Args:
        left: Alias of one side.
        right: Alias of the other side.
        columns: Columns to compare.
        indent: Indent for continuation lines.

    Returns:
        Databricks SQL boolean expression.
    """
    return f"\n{indent}OR ".join(f"NOT ({left}.{c} <=> {right}.{c})"
                                 for c in columns)


def _indent(text: str, spaces: int) -> str:
    """Indent every non-empty line of a text block."""
    pad = " " * spaces
    return "\n".join(pad + line if line.strip() else ""
                     for line in text.splitlines())


def procedure_name(model: Model) -> str:
    """Return ``schema.Load<Table>``, the load procedure of a gold model."""
    return f"{model.schema}.Load{model.name}"


def gold_procedure_sql(project: Project, model: Model) -> str:
    """Return the load procedure of a gold table (one per table).

    The table's SELECT is the first CTE of the MERGE source, so the logic
    lives in the procedure (DE Policy v2). Type 2 dimensions close the
    current version of changed rows and insert the new version in one
    MERGE. Facts, bridges and type 1 dimensions update changed rows in
    place and insert new ones.

    Args:
        project: The loaded project.
        model: A gold model.

    Returns:
        Databricks SQL: one ``CREATE OR REPLACE PROCEDURE`` statement.
    """
    spec = model.path.relative_to(project.config.root).as_posix()
    rel = project.relation(model)
    sk = model.surrogate_key
    keys = model.business_keys
    data = [c.name for c in model.data_columns]
    load = model.load
    where = ""
    if load.get("mode") == "incremental" and load.get("column"):
        where = (f"\n            WHERE source_rows.{load['column']} >= "
                 f"date_sub(RunLoadDate, {int(load.get('lookback_days', 0))})")
    select = project.resolve_sql(model.sql or "").strip().rstrip(";").strip()
    typed = ",\n".join(f"                CAST(source_rows.{c.name} AS "
                       f"{_type(c.data_type)}) AS {c.name}"
                       for c in model.columns)
    head = [
        f"-- Load {model.key} ({model.kind}"
        + (f", SCD type {model.scd_type}" if model.scd_type else "") + ").",
        "-- One stored procedure per destination table (DE Policy v2, gold "
        "code standards).",
        f"-- The SELECT comes from {spec[:-4]}.sql.",
        f"-- {GENERATED.format(spec=spec)}", "",
        f"CREATE OR REPLACE PROCEDURE {TOKENS['gold']}."
        f"{procedure_name(model)}(",
        "    RunLoadDate DATE,",
        "    RunLoadStepID STRING",
        ")",
        "LANGUAGE SQL",
        "SQL SECURITY INVOKER",
        "COMMENT " + sql_string(f"Loads {model.key} with MERGE. "
                                f"Generated by dbde from {spec}."),
        "AS BEGIN",
        "    DECLARE RunTimestamp TIMESTAMP DEFAULT current_timestamp();",
        "    DECLARE MaxKey BIGINT DEFAULT 0;",
        "",
        "    -- New surrogate keys continue from the highest key in use",
        "    -- (-1 is the unknown member).",
        "    SET MaxKey = (",
        f"        SELECT coalesce(max({sk}), 0)",
        f"        FROM {rel}",
        f"        WHERE {sk} > 0",
        "    );",
        "",
    ]
    ctes = [
        "        WITH source_rows AS (",
        _indent(select, 12),
        "        ),",
        "        typed AS (",
        "            SELECT",
        typed,
        f"            FROM source_rows{where}",
        "        )" + ("," if model.is_scd2 else ""),
    ]
    if model.is_scd2:
        merge_keys = [f"MergeKey{i}" for i in range(1, len(keys) + 1)]
        types = {c.name: _type(c.data_type) for c in model.columns}
        firsts = ", ".join(f"typed.{k} AS {m}"
                           for k, m in zip(keys, merge_keys))
        nulls = ", ".join(f"CAST(NULL AS {types[k]}) AS {m}"
                          for k, m in zip(keys, merge_keys))
        current = "\n                AND ".join(
            f"current_row.{k} = typed.{k}" for k in keys)
        ctes += [
            "        -- Every source row is staged on its business key.",
            "        -- Changed rows are staged again with a NULL key, so",
            "        -- the MERGE both closes the current version and",
            "        -- inserts the new one.",
            "        changes AS (",
            f"            SELECT {firsts}, typed.*",
            "            FROM typed",
        ]
        if data:
            ctes += [
                "            UNION ALL",
                f"            SELECT {nulls}, typed.*",
                "            FROM typed",
                f"            INNER JOIN {rel} AS current_row",
                f"                ON {current}",
                "                AND current_row.IsCurrent",
                "            WHERE " + _changed("current_row", "typed", data,
                                                "                "),
            ]
        ctes += ["        )"]
        order = ", ".join([f"changes.{k}" for k in keys]
                          + [f"changes.{merge_keys[0]} NULLS LAST"])
        source = [
            "        SELECT",
            "            changes.*,",
            f"            MaxKey + row_number() OVER (ORDER BY {order})",
            "                AS NewKey",
            "        FROM changes",
        ]
        on = "\n        AND ".join(f"target.{k} = source.{m}"
                                   for k, m in zip(keys, merge_keys))
        body = ["    MERGE INTO " + rel + " AS target", "    USING ("] \
            + ctes + source + [
                "    ) AS source",
                f"    ON {on}",
                "        AND target.IsCurrent"]
        if data:
            body += [
                "    WHEN MATCHED AND (",
                "        " + _changed("target", "source", data, "        "),
                "    ) THEN UPDATE SET",
                "        EndDate = date_sub(RunLoadDate, 1),",
                "        IsCurrent = false,",
                "        LastUpdateLoadStepID = RunLoadStepID,",
                "        LastUpdateTimestamp = RunTimestamp",
            ]
        names = [sk] + keys + data + ["StartDate", "EndDate", "IsCurrent"] \
            + AUDIT_COLUMNS
        values = (["source.NewKey"]
                  + [f"source.{c}" for c in keys + data]
                  + [f"CASE WHEN source.{merge_keys[0]} IS NULL "
                     "THEN RunLoadDate ELSE DATE'1900-01-01' END",
                     "DATE'9999-12-31'", "true", "RunLoadStepID",
                     "RunTimestamp", "RunLoadStepID", "RunTimestamp"])
    else:
        order = ", ".join(f"typed.{k}" for k in keys) or "1"
        source = [
            "        SELECT",
            "            typed.*,",
            f"            MaxKey + row_number() OVER (ORDER BY {order})",
            "                AS NewKey",
            "        FROM typed",
        ]
        on = "\n        AND ".join(f"target.{k} = source.{k}" for k in keys)
        body = ["    MERGE INTO " + rel + " AS target", "    USING ("] \
            + ctes + source + ["    ) AS source", f"    ON {on or '1 = 0'}"]
        if data:
            body += [
                "    WHEN MATCHED AND (",
                "        " + _changed("target", "source", data, "        "),
                "    ) THEN UPDATE SET",
            ] + [f"        {c} = source.{c}," for c in data] + [
                "        LastUpdateLoadStepID = RunLoadStepID,",
                "        LastUpdateTimestamp = RunTimestamp",
            ]
        names = [sk] + keys + data + AUDIT_COLUMNS
        values = (["source.NewKey"] + [f"source.{c}" for c in keys + data]
                  + ["RunLoadStepID", "RunTimestamp", "RunLoadStepID",
                     "RunTimestamp"])
    body += [
        "    WHEN NOT MATCHED THEN INSERT (",
        "        " + ",\n        ".join(names),
        "    ) VALUES (",
        "        " + ",\n        ".join(values),
        "    );",
        "END;",
        GO,
    ]
    return "\n".join(head + body) + "\n"


def ops_table_sql() -> str:
    """Return the DDL of the data quality log table."""
    return "\n".join([
        "-- Data quality results: one row per test per run.",
        f"-- {GENERATED.format(spec='dbde/render.py')}", "",
        _schema_statement("ops"), "",
        f"CREATE TABLE IF NOT EXISTS {TOKENS['gold']}.ops.DataQualityResult (",
        "    LoadStepID      STRING    NOT NULL COMMENT 'Job run that ran "
        "the test.',",
        "    Layer           STRING    NOT NULL COMMENT 'source, silver or "
        "gold.',",
        "    TableName       STRING    NOT NULL COMMENT 'schema.Table "
        "tested.',",
        "    TestName        STRING    NOT NULL COMMENT 'Test name, "
        "<kind>__<column>.',",
        "    Severity        STRING    NOT NULL COMMENT 'error stops the "
        "load; warn is logged.',",
        "    FailureCount    BIGINT    NOT NULL COMMENT 'Rows that failed "
        "(0 = pass).',",
        "    TestedTimestamp TIMESTAMP NOT NULL COMMENT 'When the test ran "
        "(UTC).'",
        ")",
        "USING DELTA",
        "COMMENT 'Data trust record: every data quality test result of "
        "every load.';",
        GO,
    ]) + "\n"


def ops_tests_sql(project: Project) -> str:
    """Return ``ops.RunDataQualityTests``, generated from every spec test.

    Args:
        project: The loaded project.

    Returns:
        Databricks SQL: one ``CREATE OR REPLACE PROCEDURE`` statement.
    """
    gold = TOKENS["gold"]
    lines = [
        "-- Runs every data quality test of one layer, logs the failure",
        "-- counts to ops.DataQualityResult and raises an error when an",
        "-- error-severity test fails, which stops the job (stale but right",
        "-- beats fresh but wrong).",
        f"-- {GENERATED.format(spec='every spec under models/')}", "",
        f"CREATE OR REPLACE PROCEDURE {gold}.ops.RunDataQualityTests(",
        "    TestLayer STRING,",
        "    RunLoadStepID STRING",
        ")",
        "LANGUAGE SQL",
        "SQL SECURITY INVOKER",
        "COMMENT 'Runs the data quality tests of one layer. Generated by "
        "dbde.'",
        "AS BEGIN",
        "    DECLARE FailedTests BIGINT DEFAULT 0;",
        "    DECLARE FailureMessage STRING DEFAULT '';",
    ]
    for layer in ("source", "silver", "gold"):
        tests = dq.all_tests(project, layer)
        if not tests:
            continue
        lines += ["", f"    IF TestLayer = '{layer}' THEN"]
        for test in tests:
            lines += [
                f"        -- {test.table}: {test.name}",
                f"        INSERT INTO {gold}.ops.DataQualityResult",
                f"        SELECT RunLoadStepID, '{layer}', '{test.table}', "
                f"'{test.name}',",
                f"            '{test.severity}', count(*), "
                "current_timestamp()",
                f"        FROM ({dq.failing_rows_sql(project, test)}) "
                "AS failing;",
            ]
        lines += ["    END IF;"]
    lines += [
        "",
        "    SET FailedTests = (",
        f"        SELECT count(*) FROM {gold}.ops.DataQualityResult",
        "        WHERE LoadStepID = RunLoadStepID AND Layer = TestLayer",
        "            AND Severity = 'error' AND FailureCount > 0",
        "    );",
        "    IF FailedTests > 0 THEN",
        "        SET FailureMessage = concat(FailedTests, ' ', TestLayer,",
        "            ' data quality test(s) failed. See',",
        "            ' ops.DataQualityResult for LoadStepID ',",
        "            RunLoadStepID, '.');",
        "        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = FailureMessage;",
        "    END IF;",
        "END;",
        GO,
    ]
    return "\n".join(lines) + "\n"


def ops_gold_loads_sql(project: Project) -> str:
    """Return ``ops.RunGoldLoads``: every gold load in dependency order.

    The daily job runs one task per load procedure; this procedure is for
    a manual reload of the whole gold layer from the SQL editor.

    Args:
        project: The loaded project.

    Returns:
        Databricks SQL: one ``CREATE OR REPLACE PROCEDURE`` statement.
    """
    lines = [
        "-- Runs every gold load procedure: dimensions first, then the",
        "-- tables that read them. For manual reloads; the daily job runs",
        "-- one task per procedure.",
        f"-- {GENERATED.format(spec='every gold spec')}", "",
        f"CREATE OR REPLACE PROCEDURE {TOKENS['gold']}.ops.RunGoldLoads(",
        "    RunLoadDate DATE,",
        "    RunLoadStepID STRING",
        ")",
        "LANGUAGE SQL",
        "SQL SECURITY INVOKER",
        "COMMENT 'Runs every gold load procedure in order. "
        "Generated by dbde.'",
        "AS BEGIN",
    ]
    for model in project.load_order(project.gold()):
        lines.append(f"    CALL {TOKENS['gold']}.{procedure_name(model)}"
                     "(RunLoadDate, RunLoadStepID);")
    lines += ["END;", GO]
    return "\n".join(lines) + "\n"


