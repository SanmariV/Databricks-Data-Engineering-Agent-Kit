def _view_description(fact: Model) -> str:
    """Return the description of a fact's metric view.

    Args:
        fact: A gold fact with measures.

    Returns:
        Text naming the measures, then the fact's description.
    """
    names = ", ".join(str(m.get("name")) for m in fact.measures)
    return (f"Metric view of {fact.name} (measures: {names}); query with "
            f"MEASURE(<name>) and GROUP BY ALL. {fact.description}")


def space_sources(project: Project,
                  space: GenieSpace) -> Tuple[List[Model], List[Model]]:
    """Return the gold tables and the facts whose metric views a space reads.

    Args:
        project: The loaded project.
        space: The Genie space.

    Returns:
        (tables, facts of metric views), known keys only, in spec order.
    """
    views = project.metric_views
    tables, metric = [], []
    for key in space.tables:
        if key in views:
            metric.append(views[key])
        elif key in project.models and project.models[key].layer == "gold":
            tables.append(project.models[key])
    return tables, metric


def stable_id(*parts: str) -> str:
    """Return a 32-character hex id that is the same on every render."""
    return hashlib.md5("\x1f".join(parts).encode("utf-8")).hexdigest()


def _lines(text: str) -> List[str]:
    """Split text into the string array the Genie API uses."""
    return (text or "").strip().splitlines(keepends=True)


def example_sql(project: Project, example: Dict[str, Any],
                catalogs: Optional[Dict[str, str]] = None) -> str:
    """Return an example query with real (or token) table names.

    Args:
        project: The loaded project.
        example: One ``examples:`` or ``benchmarks:`` entry.
        catalogs: Layer -> catalog, or None for the catalog tokens.

    Returns:
        The query with ``{{ ref() }}`` resolved and no trailing semicolon.
    """
    text = str(example.get("query") or "").replace("\r\n", "\n").strip()
    return project.resolve_sql(text, catalogs).rstrip(";").strip()


def serialized_space(project: Project, space: GenieSpace) -> Dict[str, Any]:
    """Return the Genie ``serialized_space`` (version 2) of a space.

    Args:
        project: The loaded project.
        space: The Genie space.

    Returns:
        The JSON document, with catalog tokens in every table name.
    """
    tables, facts = space_sources(project, space)
    name = space.name
    table_entries = [{"identifier": project.relation(m),
                      "description": _lines(m.description)}
                     for m in tables]
    view_entries = [{"identifier": project.metric_view_relation(m),
                     "description": _lines(_view_description(m))}
                    for m in facts]
    guidance = []
    for label, model in ([(m.name, m) for m in tables]
                         + [(m.metric_view, m) for m in facts]):
        if model.ai_instructions and not any(
                g.endswith(model.ai_instructions) for g in guidance):
            names = [label] + ([model.metric_view] if model in tables
                               and model in facts else [])
            guidance.append(f"{', '.join(names)}: {model.ai_instructions}")
    text = space.instructions
    if guidance:
        text += "\n\nTable guidance:\n" + "\n".join(
            f"- {g}" for g in guidance)
    examples = [{"id": stable_id(name, "example", str(e.get("question"))),
                 "question": [str(e.get("question") or "").strip()],
                 "sql": _lines(example_sql(project, e))}
                for e in space.examples]
    benchmarks = [{"id": stable_id(name, "benchmark", str(e.get("question"))),
                   "question": [str(e.get("question") or "").strip()],
                   "answer": [{"format": "SQL",
                               "content": _lines(example_sql(project, e))}]}
                  for e in space.benchmarks]
    samples = [{"id": stable_id(name, "sample", q), "question": [q]}
               for q in space.sample_questions]

    def by_id(items: list) -> list:
        return sorted(items, key=lambda i: i["id"])

    def by_name(items: list) -> list:
        return sorted(items, key=lambda i: i["identifier"])

    document: Dict[str, Any] = {
        "version": 2,
        "config": {"sample_questions": by_id(samples)},
        "data_sources": {"tables": by_name(table_entries),
                         "metric_views": by_name(view_entries)},
        "instructions": {
            "text_instructions": [{"id": stable_id(name, "instructions"),
                                   "content": _lines(text)}],
            "example_question_sqls": by_id(examples),
        },
    }
    if benchmarks:
        document["benchmarks"] = {"questions": by_id(benchmarks)}
    return document


def space_json(project: Project, space: GenieSpace) -> str:
    """Return the rendered ``genie/<Name>.geniespace.json`` text."""
    return json.dumps(serialized_space(project, space), indent=2,
                      ensure_ascii=False) + "\n"


def space_resource(project: Project, space: GenieSpace) -> Dict[str, Any]:
    """Return the Asset Bundle resource of a Genie space.

    Args:
        project: The loaded project.
        space: The Genie space.

    Returns:
        The ``resources:`` mapping for ``resources/genie_<name>.yml``.
    """
    groups = space.groups or ["TODO(consumer group)"]
    return {"resources": {"genie_spaces": {space.resource_name: {
        "title": space.title or space.name,
        "description": space.description,
        "warehouse_id": "${var.warehouse_id}",
        "file_path": f"../target/genie/{space.name}.geniespace.json",
        "permissions": [{"level": "CAN_RUN", "group_name": g}
                        for g in groups],
    }}}}


def grants_sql(project: Project, space: GenieSpace) -> str:
    """Return the GRANT statements a space's consumer groups need.

    Genie answers with the asking user's own permissions, so every consumer
    group needs ``SELECT`` on the space's tables and metric views.

    Args:
        project: The loaded project.
        space: The Genie space.

    Returns:
        Databricks SQL statements separated by ``-- GO`` lines.
    """
    tables, facts = space_sources(project, space)
    objects = [project.relation(m) for m in tables]
    objects += [project.metric_view_relation(m) for m in facts]
    schemas = sorted({f"${{gold_catalog}}.{m.schema}" for m in tables + facts})
    spec = space.path.relative_to(project.config.root).as_posix()
    lines = [f"-- Read access for the consumers of Genie space {space.name}.",
             f"-- {GENERATED.format(spec=spec)}", ""]
    for group in space.groups:
        principal = f"`{group}`"
        lines += [f"GRANT USE CATALOG ON CATALOG ${{gold_catalog}} "
                  f"TO {principal};", "-- GO"]
        for schema in schemas:
            lines += [f"GRANT USE SCHEMA ON SCHEMA {schema} TO {principal};",
                      "-- GO"]
        for name in objects:
            lines += [f"GRANT SELECT ON TABLE {name} TO {principal};",
                      "-- GO"]
    return "\n".join(lines) + "\n"


def run_examples(project: Project, space: GenieSpace, connection,
                 catalogs: Dict[str, str]) -> List[Tuple[str, bool, str]]:
    """Run a space's example and benchmark queries read-only.

    An example passes when it runs and returns at least one row (set
    ``allow_empty: true`` on the example to accept none). When the example
    lists ``expect_columns``, those columns must be in the result.

    Args:
        project: The loaded project.
        space: The Genie space.
        connection: Open SQL warehouse connection.
        catalogs: Layer -> catalog of the target.

    Returns:
        (question, passed, detail) per example.
    """
    from dbde import connect

    results = []
    for example in space.examples + space.benchmarks:
        question = str(example.get("question") or "")
        try:
            rows = connect.read_only_query(
                connection, example_sql(project, example, catalogs), 200)
        except Exception as exc:  # the warehouse error is the finding
            results.append((question, False, f"query failed: {exc}"))
            continue
        if not rows and not example.get("allow_empty"):
            results.append((question, False, "returned no rows"))
            continue
        missing = [c for c in example.get("expect_columns") or []
                   if rows and c not in rows[0]]
        if missing:
            results.append((question, False,
                            f"missing columns: {', '.join(missing)}"))
            continue
        results.append((question, True, f"{len(rows)} rows"))
    return results
