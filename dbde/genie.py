"""Metric views and Genie spaces, rendered from the gold specs.

A **metric view** (Unity Catalog ``WITH METRICS``) is rendered for every
fact that declares ``measures:``. It is the semantic layer: the fact is its
source, every ``references:`` column becomes a join to its dimension, and the
fact's and dimensions' descriptive columns become its dimensions. Columns
marked ``meta.pii: true`` are left out, so a metric view never exposes
personal data. Rendered to ``gold/<domain>/metric_views/Metric<Process>.sql``.

A **Genie space** is rendered from ``models/genie/<Name>.yml``::

    title: Sales analyst
    description: Answers new business questions for the distribution team.
    instructions: |
      Answer only from the data. Premium is in policy currency.
    tables:                          # gold tables and metric views (no PII)
      - sales.MetricNewBusiness
      - sales.FactNewBusiness
    sample_questions:
      - How many policies did we sell last month?
    examples:                        # question -> Databricks SQL, 3 or more
      - question: How many policies were issued per product?
        query: |
          select ProductCode, measure(NewBusinessCount) as PolicyCount
          from {{ ref('sales.MetricNewBusiness') }}
          group by all
    benchmarks: []                   # same shape; Genie's evaluation set
    permissions:
      can_run: [sales_analysts]      # groups, never people

It becomes ``genie/<Name>.geniespace.json`` (the Genie ``serialized_space``,
version 2, with catalog tokens; committed so reviewers see it) and the bundle
resource ``resources/genie_<name>.yml``. ``python -m dbde deploy`` writes the
target's copy to ``target/genie/`` with real catalog names, and the bundle
deploys the space from there.

[Spike] Confirm the metric view YAML version (1.1) and the Genie
``serialized_space`` fields against the workspace you deploy to.
"""

from __future__ import annotations

import hashlib
import json
from typing import Any, Dict, List, Optional, Tuple

import yaml

from dbde.project import Column, GenieSpace, Model, Project

NUMERIC = ("decimal", "double", "float", "real", "numeric")
GENERATED = ("Generated by `python -m dbde render` from {spec}. "
             "Do not edit: change the spec and render again.")


# --------------------------------------------------------------------------
# Metric views
# --------------------------------------------------------------------------

def join_name(column: Column) -> str:
    """Return the metric view join name of a dimension key column.

    Args:
        column: A fact column with ``references``, e.g. ``IssueDimDate_SK``.

    Returns:
        The column name without ``_SK``, e.g. ``IssueDimDate``.
    """
    return column.name[:-3] if column.name.endswith("_SK") else column.name


def _is_dimension_column(column: Column) -> bool:
    """Return True when a column can slice a metric view.

    Args:
        column: A gold column.

    Returns:
        False for personal data, surrogate keys and money / measure-like
        numeric columns; True otherwise.
    """
    if column.pii or column.name.endswith("_SK"):
        return False
    return not column.data_type.startswith(NUMERIC)


def _with_synonyms(entry: Dict[str, Any], synonyms: Any) -> Dict[str, Any]:
    """Add ``synonyms`` to a metric view entry when there are any."""
    if isinstance(synonyms, list) and synonyms:
        entry["synonyms"] = [str(s) for s in synonyms]
    return entry


def metric_view_dimensions(project: Project,
                           fact: Model) -> List[Dict[str, Any]]:
    """Return the dimensions of a fact's metric view.

    The fact's own descriptive columns come first, then the descriptive
    columns of every dimension it references. A name that repeats is
    prefixed with the join name (``IssueDimDateCalendarYear``).

    Args:
        project: The loaded project.
        fact: A fact with measures.

    Returns:
        ``name`` / ``expr`` / ``comment`` mappings.
    """
    out: List[Dict[str, Any]] = []
    names: set = set()

    def add(name: str, expr: str, column: Column) -> None:
        names.add(name)
        out.append(_with_synonyms({"name": name, "expr": expr,
                                   "comment": _text(column.description)},
                                  column.synonyms))

    for column in fact.columns:
        if _is_dimension_column(column):
            add(column.name, f"source.{column.name}", column)
    for column in fact.columns:
        dim = project.models.get(str(column.references or ""))
        if not dim:
            continue
        alias = join_name(column)
        for attribute in dim.columns:
            if not _is_dimension_column(attribute):
                continue
            name = attribute.name
            if name in names:
                name = f"{alias}{attribute.name}"
            add(name, f"{alias}.{attribute.name}", attribute)
    return out


def metric_view_yaml(project: Project, fact: Model) -> Dict[str, Any]:
    """Return the metric view definition of a fact (YAML version 1.1).

    Args:
        project: The loaded project.
        fact: A fact with measures.

    Returns:
        The definition as a mapping.
    """
    joins = []
    for column in fact.columns:
        dim = project.models.get(str(column.references or ""))
        if not dim:
            continue
        alias = join_name(column)
        joins.append({"name": alias, "source": project.relation(dim),
                      "on": f"source.{column.name} = "
                            f"{alias}.{dim.surrogate_key}"})
    measures = []
    for measure in fact.measures:
        measures.append(_with_synonyms({
            "name": str(measure.get("name")),
            "expr": " ".join(str(measure.get("expression") or "").split()),
            "comment": _text(measure.get("description"))},
            measure.get("synonyms")))
    body: Dict[str, Any] = {"version": "1.1",
                            "comment": _text(_view_description(fact)),
                            "source": project.relation(fact)}
    if joins:
        body["joins"] = joins
    body["dimensions"] = metric_view_dimensions(project, fact)
    body["measures"] = measures
    return body


def _text(value: Any) -> str:
    """Return text on one line (descriptions may be folded YAML)."""
    return " ".join(str(value or "").split())


def metric_view_sql(project: Project, fact: Model) -> str:
    """Return the ``CREATE OR REPLACE VIEW ... WITH METRICS`` statement.

    Args:
        project: The loaded project.
        fact: A fact with measures.

    Returns:
        Databricks SQL, one statement.
    """
    spec = fact.path.relative_to(project.config.root).as_posix()
    body = yaml.safe_dump(metric_view_yaml(project, fact), sort_keys=False,
                          width=76, allow_unicode=True)
    return "\n".join([
        f"-- Metric view over {fact.key}: the measures of the fact, sliced by",
        "-- its own columns and those of the dimensions it references.",
        "-- Columns marked meta.pii are left out.",
        f"-- {GENERATED.format(spec=spec)}", "",
        f"CREATE OR REPLACE VIEW {project.metric_view_relation(fact)}",
        "WITH METRICS",
        "LANGUAGE YAML",
        "AS $$",
        body.rstrip("\n"),
        "$$;",
    ]) + "\n"


