def main(catalogs: dict, load_date: str, load_step_id: str,
         full_refresh: bool) -> int:
    """Build the integrated rows and merge them into the silver table.

    Args:
        catalogs: Layer (``bronze``, ``silver``) -> catalog name.
        load_date: Business date being loaded (``yyyy-mm-dd``); empty means
            yesterday (UTC).
        load_step_id: Load step identifier written to the audit columns.
        full_refresh: Unused; the query decides what it reads.

    Returns:
        The number of distinct business keys merged.
    """
    target = f"{catalogs['silver']}.{TABLE}"
    rows = spark.sql(silver.substitute(QUERY, catalogs), args=None)
    conformed = silver.conform(rows, COLUMNS, [])
    silver.assert_unique(conformed, BUSINESS_KEYS)
    silver.ensure_table(spark, target, COLUMNS, BUSINESS_KEYS, DESCRIPTION)
    return silver.merge_into(spark, target, conformed, BUSINESS_KEYS,
                             load_step_id)

